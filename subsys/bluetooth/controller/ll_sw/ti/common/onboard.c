extern uint8 LL_Rand( uint8 *, uint8 );

/*********************************************************************
 * @fn        Onboard_rand
 *
 * @brief    Random number generator
 *
 * @param   none
 *
 * @return  uint16 - new random number
 *
 *********************************************************************/
uint16 Onboard_rand( void )
{
  uint16 randNum;

  LL_Rand( (uint8 *)&randNum, 2 );

  return ( randNum );
}

